"""
AuroraAI — Chat Router

Exposes:
  POST /api/aurora/chat   — main chat endpoint
  GET  /api/aurora/health — health check (DB + LLM connectivity)
"""

from fastapi import APIRouter, Header, HTTPException
from app.models.schemas import ChatRequest, ChatResponse, HealthResponse
from app.graph.pipeline import run_pipeline
from app.db.connection import check_connection
from app.config import get_settings
import logging
import time

router  = APIRouter()
logger  = logging.getLogger(__name__)
settings = get_settings()


@router.post("/chat", response_model=ChatResponse)
async def chat(request: ChatRequest,
               x_customer_id: str | None = Header(default=None)) -> ChatResponse:
    """
    Main chat endpoint — accepts a plain-English query and returns
    a natural-language response generated by the three-agent pipeline.

    Spec: FR-AI-01 — handle at least 10 distinct query types within 5 seconds
    for 90% of requests (NFR-P-03).
    """
    logger.info("Chat request — message: '%s' | account_id: %s",
                request.message[:80], request.account_id)

    # Identity comes only from the X-Customer-Id header that the API gateway sets after it has
    # validated the JWT (it overwrites any value the client sends). The request body is ignored.
    verified_customer_id = x_customer_id.strip() if x_customer_id and x_customer_id.strip().isdigit() else None

    start = time.time()

    try:
        state = run_pipeline(
            message=request.message,
            account_id=request.account_id,
            customer_id=verified_customer_id,   # from the gateway, never from the request body
        )

        elapsed = time.time() - start
        logger.info("Pipeline completed in %.2fs", elapsed)

        return ChatResponse(
            response=state.final_response or "I'm sorry, I couldn't process that query.",
            query_type=state.intent.query_type if state.intent else "unknown",
            result_count=len(state.sql_result.rows) if state.sql_result else 0,
            data=state.sql_result.rows if state.sql_result else None,
        )

    except Exception as e:
        logger.error("Chat endpoint error: %s", e, exc_info=True)
        raise HTTPException(
            status_code=500,
            detail="An unexpected error occurred. Please try again."
        )


@router.get("/health", response_model=HealthResponse)
async def health() -> HealthResponse:
    """
    Health check — confirms the AuroraAI service is running,
    the database is reachable, and the configured LLM backend is set.
    Spec: GET /api/aurora/health
    """
    db_ok = check_connection()

    model = (settings.ollama_model if settings.llm_backend == "ollama"
             else settings.claude_model)

    return HealthResponse(
        status="ok" if db_ok else "degraded",
        db_connected=db_ok,
        llm_backend=settings.llm_backend,
        model=model,
    )
